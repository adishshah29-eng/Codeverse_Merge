/* XOR variant: nothing readable in .rodata; decode happens at runtime. */
#include <stdio.h>
#include <string.h>

static const unsigned char P[] = { 0x28, 0x69, 0x2c, 0x69, 0x28, 0x29, 0x69, 0x05, 0x37, 0x69, 0x05, 0x2a, 0x36, 0x29 };
static const unsigned char F[] = { 0x3c, 0x36, 0x3b, 0x3d, 0x21, 0x29, 0x2e, 0x3b, 0x3d, 0x3f, 0x6b, 0x05, 0x39, 0x36, 0x3f, 0x3b, 0x28, 0x3f, 0x3e, 0x05, 0x35, 0x34, 0x05, 0x2e, 0x35, 0x05, 0x2e, 0x32, 0x3f, 0x05, 0x34, 0x3f, 0x22, 0x2e, 0x27 };

static void dec(const unsigned char *in, size_t n, char *out) {
    for (size_t i = 0; i < n; i++) out[i] = (char)(in[i] ^ 0x5A);
    out[n] = 0;
}

int main(void) {
    char buf[64], pw[64], flag[96];
    dec(P, sizeof P, pw);
    printf("Password: ");
    if (scanf("%63s", buf) != 1) return 1;
    if (strcmp(buf, pw) == 0) {
        dec(F, sizeof F, flag);
        printf("%s\n", flag);
    } else
        printf("Access denied\n");
    return 0;
}
